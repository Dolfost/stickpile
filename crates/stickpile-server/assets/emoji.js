// stickpile emoji picker. Plain JavaScript, no build step, loaded with
// `defer` from /static/emoji.js before upload.js (the CSP allows no inline
// scripts).
//
// Text fields marked with [data-emoji-picker] (the item editor's Emojis
// fields, also when htmx swaps them in) get a button that opens an inline
// panel: a search box (CLDR names and keywords plus the slang the server's
// search knows, so "laugh" finds 😂), category tabs, the recently used
// emojis (localStorage) and a grid of emojis. A pick appends the emoji to
// the field, separated by a space, unless it is there already, and fires
// `input`; the panel stays open for more. upload.js builds the tray's field
// itself and calls window.stickpileEmoji.attach(input).
//
// The data (/static/emoji.json, generated by scripts/gen-emoji-data.py from
// Unicode data) is fetched on the first open, never with the page.
//
// Keyboard: the grid, the recent row and the tabs are one Tab stop each
// (arrow keys move inside, Home/End jump); Enter in the search box picks the
// first result and ↓ moves to the results; Escape closes the panel and puts
// focus back on its button. A click outside closes it too.
(function () {
  "use strict";

  var script = document.currentScript;
  var DATA_URL = (script && script.getAttribute("data-emoji-data")) || "/static/emoji.json";
  var RECENT_KEY = "stickpile.recentEmojis";
  var RECENT_MAX = 16;
  var MAX_RESULTS = 150;
  var SVG_NS = "http://www.w3.org/2000/svg";

  var dataPromise = null;
  var current = null; // the open picker
  var nextId = 1;

  // ---- helpers ---------------------------------------------------------

  function el(tag, cls, text) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text != null) e.textContent = text;
    return e;
  }

  function smiley() {
    var svg = document.createElementNS(SVG_NS, "svg");
    svg.setAttribute("class", "icon");
    svg.setAttribute("viewBox", "0 0 24 24");
    svg.setAttribute("aria-hidden", "true");
    svg.setAttribute("focusable", "false");
    svg.setAttribute("fill", "none");
    svg.setAttribute("stroke", "currentColor");
    svg.setAttribute("stroke-width", "2");
    svg.setAttribute("stroke-linecap", "round");
    svg.setAttribute("stroke-linejoin", "round");
    ["M12 3a9 9 0 1 0 0 18 9 9 0 0 0 0-18z", "M8.5 14.5a4.5 4.5 0 0 0 7 0", "M9 9.5h.01", "M15 9.5h.01"].forEach(
      function (d) {
        var p = document.createElementNS(SVG_NS, "path");
        p.setAttribute("d", d);
        svg.appendChild(p);
      }
    );
    return svg;
  }

  // Lowercase, without accents ("piñata" -> "pinata"), straight apostrophes.
  function fold(s) {
    s = String(s || "").toLowerCase();
    if (s.normalize) s = s.normalize("NFD").replace(/[̀-ͯ]/g, "");
    return s.replace(/[‘’]/g, "'");
  }

  // Search words; "t-rex" also gives "t" and "rex".
  function words(s) {
    var out = [];
    fold(s)
      .split(/[\s:,()"“”]+/)
      .forEach(function (w) {
        if (!w) return;
        out.push(w);
        if (w.indexOf("-") > 0) {
          w.split("-").forEach(function (p) {
            if (p) out.push(p);
          });
        }
      });
    return out;
  }

  // Without variation selectors, to compare "❤" with "❤️".
  function bare(s) {
    return String(s).replace(/️/g, "");
  }

  // ---- data --------------------------------------------------------------

  function load() {
    if (!dataPromise) {
      dataPromise = fetch(DATA_URL, { credentials: "same-origin" })
        .then(function (r) {
          if (!r.ok) throw new Error("HTTP " + r.status);
          return r.json();
        })
        .then(prepare);
      dataPromise.catch(function () {
        dataPromise = null; // try again on the next open
      });
    }
    return dataPromise;
  }

  function prepare(json) {
    var all = [];
    var byBare = {};
    var groups = json.groups.map(function (g) {
      return {
        name: g[0],
        icon: g[1],
        items: g[2].map(function (r) {
          var e = { char: r[0], name: r[1], nameWords: words(r[1]), keyWords: words(r[2]), order: all.length };
          all.push(e);
          byBare[bare(r[0])] = e;
          return e;
        }),
      };
    });
    return { groups: groups, all: all, byBare: byBare };
  }

  // How well one query word matches (lower is better), -1 for not at all:
  // a word of the name (the first word best), then a keyword; whole words
  // before prefixes.
  function termScore(e, t) {
    var best = -1;
    for (var i = 0; i < e.nameWords.length; i++) {
      var w = e.nameWords[i];
      var s = w === t ? 0 : w.indexOf(t) === 0 ? 2 : -1;
      if (s >= 0 && i > 0) s += 1;
      if (s >= 0 && (best < 0 || s < best)) best = s;
    }
    if (best >= 0 && best < 2) return best;
    for (var k = 0; k < e.keyWords.length; k++) {
      var kw = e.keyWords[k];
      var ks = kw === t ? 2.5 : kw.indexOf(t) === 0 ? 4 : -1;
      if (ks >= 0 && (best < 0 || ks < best)) best = ks;
    }
    return best;
  }

  function search(data, query) {
    var q = query.trim();
    if (!q) return [];
    // An emoji typed or pasted into the search box finds itself.
    var direct = data.byBare[bare(q)];
    if (direct) return [direct];
    var terms = words(q);
    if (!terms.length) return [];
    var whole = terms.join(" ");
    var scored = [];
    data.all.forEach(function (e) {
      var total = 0;
      for (var i = 0; i < terms.length; i++) {
        var s = termScore(e, terms[i]);
        if (s < 0) return;
        total += s;
      }
      if (e.nameWords.join(" ") === whole) total -= 10;
      scored.push({ score: total, e: e });
    });
    scored.sort(function (a, b) {
      return a.score - b.score || a.e.order - b.e.order;
    });
    return scored.slice(0, MAX_RESULTS).map(function (x) {
      return x.e;
    });
  }

  // ---- recently used -------------------------------------------------------

  function recent() {
    try {
      var list = JSON.parse(window.localStorage.getItem(RECENT_KEY) || "[]");
      if (!Array.isArray(list)) return [];
      return list.filter(function (x) {
        return typeof x === "string";
      });
    } catch (e) {
      return [];
    }
  }

  function remember(ch) {
    var list = recent().filter(function (x) {
      return bare(x) !== bare(ch);
    });
    list.unshift(ch);
    try {
      window.localStorage.setItem(RECENT_KEY, JSON.stringify(list.slice(0, RECENT_MAX)));
    } catch (e) {
      /* private mode or storage disabled */
    }
  }

  // ---- roving tabindex -----------------------------------------------------

  // Buttons of a group: one of them is in the Tab order.
  function roving(container) {
    return Array.prototype.slice.call(container.querySelectorAll("button"));
  }

  function setRoving(buttons, index) {
    buttons.forEach(function (b, i) {
      b.tabIndex = i === index ? 0 : -1;
    });
  }

  function moveTo(buttons, index) {
    if (!buttons.length) return;
    var i = Math.max(0, Math.min(buttons.length - 1, index));
    setRoving(buttons, i);
    buttons[i].focus();
    return buttons[i];
  }

  // Buttons per row of a wrapping grid.
  function columns(buttons) {
    if (buttons.length < 2) return 1;
    var top = buttons[0].offsetTop;
    for (var i = 1; i < buttons.length; i++) if (buttons[i].offsetTop !== top) return i;
    return buttons.length;
  }

  // Arrow keys in a grid of buttons; `up` runs when ↑ leaves the first row.
  function gridKey(ev, container, up) {
    var buttons = roving(container);
    var i = buttons.indexOf(document.activeElement);
    if (i < 0) return false;
    var cols = columns(buttons);
    var to = null;
    switch (ev.key) {
      case "ArrowLeft":
        to = i - 1;
        break;
      case "ArrowRight":
        to = i + 1;
        break;
      case "ArrowUp":
        if (i < cols) {
          if (up) {
            ev.preventDefault();
            up();
            return true;
          }
          to = i;
        } else to = i - cols;
        break;
      case "ArrowDown":
        // Into a shorter last row: its last button.
        if (i + cols < buttons.length) to = i + cols;
        else to = Math.floor(i / cols) < Math.floor((buttons.length - 1) / cols) ? buttons.length - 1 : i;
        break;
      case "Home":
        to = ev.ctrlKey ? 0 : i - (i % cols);
        break;
      case "End":
        to = ev.ctrlKey ? buttons.length - 1 : Math.min(buttons.length - 1, i - (i % cols) + cols - 1);
        break;
      case "PageUp":
        to = i - cols * 4;
        break;
      case "PageDown":
        to = Math.min(buttons.length - 1, i + cols * 4);
        break;
      default:
        return false;
    }
    ev.preventDefault();
    moveTo(buttons, to);
    return true;
  }

  // ---- one picker per field -------------------------------------------------

  function attach(input) {
    if (!input || input.tagName !== "INPUT" || input.getAttribute("data-emoji-ready")) return;
    input.setAttribute("data-emoji-ready", "1");
    var hadFocus = document.activeElement === input;
    var start = input.selectionStart;
    var end = input.selectionEnd;

    // The field and its button share a line.
    var wrap = el("span", "emoji-field");
    input.parentNode.insertBefore(wrap, input);
    wrap.appendChild(input);
    var toggle = el("button", "emoji-toggle");
    toggle.type = "button";
    toggle.setAttribute("aria-label", "Choose emojis");
    toggle.title = "Choose emojis";
    toggle.setAttribute("aria-expanded", "false");
    toggle.appendChild(smiley());
    wrap.appendChild(toggle);
    if (hadFocus) {
      // Moving the field took its focus.
      input.focus({ preventScroll: true });
      try {
        input.setSelectionRange(start, end);
      } catch (e) {
        /* not a text field */
      }
    }

    var p = { input: input, wrap: wrap, toggle: toggle, panel: null, group: 0, data: null };
    toggle.addEventListener("click", function () {
      if (isOpen(p)) close(p, false);
      else open(p);
    });
    // Escape in the field closes the panel first (before app.js cancels an
    // inline edit).
    input.addEventListener("keydown", function (ev) {
      if (ev.key === "Escape" && isOpen(p)) {
        ev.preventDefault();
        ev.stopPropagation();
        close(p, false);
      }
    });
  }

  function isOpen(p) {
    return !!p.panel && !p.panel.hidden && p.wrap.isConnected;
  }

  function build(p) {
    var id = "emoji-panel-" + nextId++;
    var panel = el("div", "emoji-panel");
    panel.id = id;
    panel.setAttribute("role", "group");
    panel.setAttribute("aria-label", "Emoji picker");
    panel.hidden = true;

    var searchBox = el("input", "emoji-search");
    searchBox.type = "search";
    searchBox.placeholder = "Search emojis";
    searchBox.setAttribute("aria-label", "Search emojis");
    searchBox.autocomplete = "off";
    searchBox.spellcheck = false;
    searchBox.setAttribute("enterkeyhint", "done");

    var tabs = el("div", "emoji-tabs");
    tabs.setAttribute("role", "tablist");
    tabs.setAttribute("aria-label", "Categories");

    var recentBox = el("div", "emoji-recent");
    var recentLabel = el("span", "emoji-label", "Recently used");
    recentLabel.id = id + "-recent";
    var recentRow = el("div", "emoji-row");
    recentRow.setAttribute("role", "group");
    recentRow.setAttribute("aria-labelledby", recentLabel.id);
    recentBox.appendChild(recentLabel);
    recentBox.appendChild(recentRow);
    recentBox.hidden = true;

    var status = el("p", "emoji-status");
    status.setAttribute("role", "status");
    status.setAttribute("aria-live", "polite");

    var grid = el("div", "emoji-grid");
    grid.id = id + "-grid";
    grid.setAttribute("role", "group");
    // Firefox makes scrolling boxes a Tab stop of their own; the buttons
    // inside are the stop.
    grid.tabIndex = -1;
    tabs.tabIndex = -1;
    searchBox.setAttribute("aria-controls", grid.id);

    [searchBox, tabs, recentBox, status, grid].forEach(function (n) {
      panel.appendChild(n);
    });
    p.wrap.parentNode.insertBefore(panel, p.wrap.nextSibling);
    p.toggle.setAttribute("aria-controls", id);
    p.panel = panel;
    p.searchBox = searchBox;
    p.tabs = tabs;
    p.recentBox = recentBox;
    p.recentRow = recentRow;
    p.status = status;
    p.grid = grid;
    p.shown = []; // the emojis in the grid

    searchBox.addEventListener("input", function (ev) {
      ev.stopPropagation(); // not a field of the form
      showResults(p);
    });
    searchBox.addEventListener("change", function (ev) {
      ev.stopPropagation();
    });
    searchBox.addEventListener("keydown", function (ev) {
      if (ev.key === "Enter" && !ev.isComposing) {
        // Never submit the form from here.
        ev.preventDefault();
        if (searchBox.value.trim() && p.shown.length) pick(p, p.shown[0]);
      } else if (ev.key === "ArrowDown" && p.shown.length) {
        ev.preventDefault();
        var buttons = roving(grid);
        moveTo(buttons, Math.max(0, buttons.indexOf(grid.querySelector("button[tabindex='0']"))));
      }
    });

    tabs.addEventListener("click", function (ev) {
      var tab = ev.target instanceof Element && ev.target.closest("[role=tab]");
      if (tab) selectGroup(p, +tab.getAttribute("data-group"), false);
    });
    tabs.addEventListener("keydown", function (ev) {
      var buttons = roving(tabs);
      var i = buttons.indexOf(document.activeElement);
      if (i < 0) return;
      var to = { ArrowLeft: i - 1, ArrowRight: i + 1, Home: 0, End: buttons.length - 1 }[ev.key];
      if (to === undefined) return;
      ev.preventDefault();
      to = (to + buttons.length) % buttons.length;
      selectGroup(p, to, true);
    });

    [grid, recentRow].forEach(function (box) {
      box.addEventListener("click", function (ev) {
        var b = ev.target instanceof Element && ev.target.closest("button[data-emoji]");
        if (!b || !p.data) return;
        var e = p.data.byBare[bare(b.getAttribute("data-emoji"))];
        if (e) {
          setRoving(roving(box), roving(box).indexOf(b));
          pick(p, e);
        }
      });
      box.addEventListener("keydown", function (ev) {
        gridKey(
          ev,
          box,
          box === grid
            ? function () {
                searchBox.focus();
              }
            : null
        );
      });
    });

    panel.addEventListener("keydown", function (ev) {
      if (ev.key === "Escape") {
        ev.preventDefault();
        ev.stopPropagation(); // app.js would cancel an inline edit
        close(p, true);
      }
    });
    // Keyboard focus leaving the field and the panel closes it.
    [p.wrap, panel].forEach(function (n) {
      n.addEventListener("focusout", function (ev) {
        var to = ev.relatedTarget;
        if (to instanceof Node && !p.wrap.contains(to) && !panel.contains(to)) close(p, false);
      });
    });
  }

  function emojiButton(e) {
    var b = el("button", "emoji-btn", e.char);
    b.type = "button";
    b.tabIndex = -1;
    b.setAttribute("data-emoji", e.char);
    b.setAttribute("aria-label", e.name);
    b.title = e.name;
    return b;
  }

  function fill(box, list) {
    var frag = document.createDocumentFragment();
    list.forEach(function (e) {
      frag.appendChild(emojiButton(e));
    });
    box.textContent = "";
    box.appendChild(frag);
    var buttons = roving(box);
    if (buttons.length) buttons[0].tabIndex = 0;
  }

  function renderTabs(p) {
    p.tabs.textContent = "";
    p.data.groups.forEach(function (g, i) {
      var t = el("button", "emoji-tab", g.icon);
      t.type = "button";
      t.id = p.panel.id + "-tab-" + i;
      t.setAttribute("role", "tab");
      t.setAttribute("aria-label", g.name);
      t.title = g.name;
      t.setAttribute("aria-controls", p.grid.id);
      t.setAttribute("data-group", String(i));
      p.tabs.appendChild(t);
    });
  }

  function renderRecent(p) {
    var list = [];
    recent().forEach(function (ch) {
      var e = p.data.byBare[bare(ch)];
      if (e) list.push(e);
    });
    fill(p.recentRow, list);
    p.recentBox.hidden = !list.length || !!p.searchBox.value.trim();
  }

  function markTab(p, i) {
    p.group = i;
    var tabs = roving(p.tabs);
    tabs.forEach(function (t, k) {
      t.setAttribute("aria-selected", k === i ? "true" : "false");
    });
    setRoving(tabs, i);
    return tabs[i];
  }

  // A category: the search is cleared.
  function selectGroup(p, i, focusTab) {
    var tab = markTab(p, i);
    if (focusTab && tab) tab.focus();
    p.searchBox.value = "";
    showResults(p);
  }

  // The grid shows the search results, or the selected category.
  function showResults(p) {
    if (!p.data) return; // still loading; shown when it arrives
    var q = p.searchBox.value.trim();
    var g = p.data.groups[p.group];
    var list;
    if (q) {
      list = search(p.data, q);
      p.grid.setAttribute("aria-label", "Search results");
      p.status.textContent = list.length
        ? list.length === 1
          ? "1 emoji"
          : list.length + (list.length === MAX_RESULTS ? "+" : "") + " emojis"
        : "No emoji matches “" + q + "”.";
    } else {
      list = g.items;
      p.grid.setAttribute("aria-label", g.name);
      p.status.textContent = "";
    }
    p.tabs.classList.toggle("searching", !!q);
    p.recentBox.hidden = !!q || !p.recentRow.firstChild;
    p.shown = list;
    fill(p.grid, list);
    p.grid.scrollTop = 0;
  }

  function open(p) {
    if (current && current !== p) close(current, false);
    if (!p.panel) build(p);
    current = p;
    p.panel.hidden = false;
    p.toggle.setAttribute("aria-expanded", "true");
    p.searchBox.value = "";
    p.searchBox.focus();
    if (p.data) {
      renderRecent(p);
      showResults(p);
      return;
    }
    p.status.textContent = "Loading emojis…";
    load().then(
      function (data) {
        if (p.data) return;
        p.data = data;
        renderTabs(p);
        markTab(p, p.group);
        renderRecent(p);
        showResults(p); // with what was typed meanwhile
      },
      function (err) {
        var why = err && err.message ? err.message : String(err);
        p.status.textContent = "Could not load the emojis (" + why + "). Close the panel and try again.";
      }
    );
  }

  function close(p, restoreFocus) {
    if (!p.panel) return;
    p.panel.hidden = true;
    p.toggle.setAttribute("aria-expanded", "false");
    if (current === p) current = null;
    if (restoreFocus && p.toggle.isConnected) p.toggle.focus();
  }

  // Append to the field (space-separated, the field's format) unless it is
  // there already, and tell the page.
  function pick(p, e) {
    var input = p.input;
    var have = input.value.split(/[\s,]+/).some(function (x) {
      return x && bare(x) === bare(e.char);
    });
    if (have) {
      p.status.textContent = e.char + " is already in the field.";
    } else {
      var v = input.value.replace(/\s+$/, "");
      input.value = v ? v + " " + e.char : e.char;
      input.dispatchEvent(new Event("input", { bubbles: true }));
      p.status.textContent = "Added " + e.char + " " + e.name + ".";
    }
    // The recent row updates on the next open, so nothing jumps now.
    remember(e.char);
  }

  // ---- page-wide -----------------------------------------------------------

  document.addEventListener(
    "pointerdown",
    function (ev) {
      var p = current;
      if (!p) return;
      if (!p.wrap.isConnected) {
        current = null;
        return;
      }
      var t = ev.target;
      if (t instanceof Node && (p.wrap.contains(t) || p.panel.contains(t))) return;
      close(p, false);
    },
    true
  );

  function enhance(root) {
    if (!root || !root.querySelectorAll) return;
    if (root.matches && root.matches("input[data-emoji-picker]")) attach(root);
    root.querySelectorAll("input[data-emoji-picker]").forEach(attach);
  }

  window.stickpileEmoji = { attach: attach };

  document.addEventListener("htmx:load", function (e) {
    enhance(e.target);
  });
  enhance(document);
})();
