// stickpile emoji picker. Plain JavaScript, no build step, loaded with
// `defer` from /static/emoji.js before upload.js (the CSP allows no inline
// scripts).
//
// Text fields marked with [data-emoji-picker] (the item editor's Emojis
// fields, also when htmx swaps them in) get a button that opens an inline
// panel: a search box (CLDR names and keywords plus the slang the server's
// search knows, so "laugh" finds 😂), category tabs, the recently used
// emojis (localStorage) and a grid of emojis. A pick appends the emoji to
// the field, separated by a space, unless it is there already, and fires
// `input`; the panel stays open for more. upload.js builds the tray's field
// itself and calls window.stickpileEmoji.attach(input).
//
// Typing ":" in the field searches without the panel: ":cat" lists the best
// matches under the field (the field is a combobox; see "':' suggestions"
// below), and Space or Enter puts the highlighted one in place of ":cat".
//
// The data (/static/emoji.json, generated by scripts/gen-emoji-data.py from
// Unicode data) is fetched on the first open or ":", never with the page.
//
// Keyboard: the grid, the recent row and the tabs are one Tab stop each
// (arrow keys move inside, Home/End jump); Enter in the search box picks the
// first result and ↓ moves to the results; Escape closes the panel and puts
// focus back on its button. A click outside closes it too.
(function () {
  "use strict";

  var script = document.currentScript;
  var DATA_URL = (script && script.getAttribute("data-emoji-data")) || "/static/emoji.json";
  var RECENT_KEY = "stickpile.recentEmojis";
  var RECENT_MAX = 16;
  var MAX_RESULTS = 150;
  var SVG_NS = "http://www.w3.org/2000/svg";

  var AC_MAX = 8; // suggestions under the field
  var dataPromise = null;
  var loaded = null; // the data, once fetched
  var current = null; // the open picker
  var acCurrent = null; // the field whose ":" suggestions are open
  var nextId = 1;

  // ---- helpers ---------------------------------------------------------

  function el(tag, cls, text) {
    var e = document.createElement(tag);
    if (cls) e.className = cls;
    if (text != null) e.textContent = text;
    return e;
  }

  function smiley() {
    var svg = document.createElementNS(SVG_NS, "svg");
    svg.setAttribute("class", "icon");
    svg.setAttribute("viewBox", "0 0 24 24");
    svg.setAttribute("aria-hidden", "true");
    svg.setAttribute("focusable", "false");
    svg.setAttribute("fill", "none");
    svg.setAttribute("stroke", "currentColor");
    svg.setAttribute("stroke-width", "2");
    svg.setAttribute("stroke-linecap", "round");
    svg.setAttribute("stroke-linejoin", "round");
    ["M12 3a9 9 0 1 0 0 18 9 9 0 0 0 0-18z", "M8.5 14.5a4.5 4.5 0 0 0 7 0", "M9 9.5h.01", "M15 9.5h.01"].forEach(
      function (d) {
        var p = document.createElementNS(SVG_NS, "path");
        p.setAttribute("d", d);
        svg.appendChild(p);
      }
    );
    return svg;
  }

  // Lowercase, without accents ("piñata" -> "pinata"), straight apostrophes.
  function fold(s) {
    s = String(s || "").toLowerCase();
    if (s.normalize) s = s.normalize("NFD").replace(/[̀-ͯ]/g, "");
    return s.replace(/[‘’]/g, "'");
  }

  // Whole words: spaces, and underscores as in ":thumbs_up".
  function plainWords(s) {
    return fold(s)
      .split(/[\s:,()"“”_]+/)
      .filter(Boolean);
  }

  // Search words; "t-rex" also gives "t" and "rex".
  function words(s) {
    var out = [];
    plainWords(s).forEach(function (w) {
      out.push(w);
      if (w.indexOf("-") > 0) {
        w.split("-").forEach(function (p) {
          if (p) out.push(p);
        });
      }
    });
    return out;
  }

  // Without variation selectors, to compare "❤" with "❤️".
  function bare(s) {
    return String(s).replace(/️/g, "");
  }

  // ---- data --------------------------------------------------------------

  function load() {
    if (!dataPromise) {
      dataPromise = fetch(DATA_URL, { credentials: "same-origin" })
        .then(function (r) {
          if (!r.ok) throw new Error("HTTP " + r.status);
          return r.json();
        })
        .then(prepare)
        .then(function (data) {
          loaded = data;
          return data;
        });
      dataPromise.catch(function () {
        dataPromise = null; // try again on the next open
      });
    }
    return dataPromise;
  }

  var UNRANKED = 1e6;

  function prepare(json) {
    var all = [];
    var byBare = {};
    // The emojis of the server's search vocabulary, roughly most used on
    // stickers first: a tie-breaker, and the suggestions for a bare ":".
    var rank = Object.create(null);
    (json.common || []).forEach(function (ch, i) {
      if (!(bare(ch) in rank)) rank[bare(ch)] = i;
    });
    var groups = json.groups.map(function (g) {
      return {
        name: g[0],
        icon: g[1],
        items: g[2].map(function (r) {
          var plain = plainWords(r[1]);
          // "cat face" is as much a "cat" as 🐈 is.
          var core = plain.filter(function (w) {
            return w !== "face";
          });
          if (!core.length) core = plain;
          var e = {
            char: r[0],
            name: r[1],
            nameWords: words(r[1]),
            full: plain.join(" "),
            core: core.join(" "),
            coreLen: core.length,
            terms: words(r[3] || ""),
            keyWords: words(r[2]),
            rank: bare(r[0]) in rank ? rank[bare(r[0])] : UNRANKED,
            order: all.length,
          };
          all.push(e);
          byBare[bare(r[0])] = e;
          return e;
        }),
      };
    });
    var common = [];
    (json.common || []).forEach(function (ch) {
      var e = byBare[bare(ch)];
      if (e && common.indexOf(e) < 0) common.push(e);
    });
    return { groups: groups, all: all, byBare: byBare, common: common };
  }

  // How well one query word matches (lower is better), -1 for not at all:
  // a curated term (the slang of the server's search: "laugh" is 😂) best,
  // then a word of the name (the first word better), then a CLDR keyword;
  // whole words before prefixes.
  function termScore(e, t) {
    var best = UNRANKED;
    var i, w, s;
    for (i = 0; i < e.terms.length; i++) {
      w = e.terms[i];
      s = w === t ? 0 : w.indexOf(t) === 0 ? 1.5 : UNRANKED;
      if (s < best) best = s;
    }
    if (best === 0) return 0;
    for (i = 0; i < e.nameWords.length; i++) {
      w = e.nameWords[i];
      s = w === t ? 0.5 : w.indexOf(t) === 0 ? 2 : UNRANKED;
      if (i > 0) s += s < 2 ? 0.5 : 1;
      if (s < best) best = s;
    }
    if (best <= 2.5) return best;
    for (i = 0; i < e.keyWords.length; i++) {
      w = e.keyWords[i];
      s = w === t ? 2.5 : w.indexOf(t) === 0 ? 4 : UNRANKED;
      if (s < best) best = s;
    }
    return best < UNRANKED ? best : -1;
  }

  // Best first: the summed term scores; a whole name ("cat" for 🐱 and 🐈,
  // "thumbs_up") and a one-word name being typed ("ca") go up. Ties: the
  // shorter name when the query is a word of it ("heart": ❤️ before 😍),
  // then the order of `common`, then the Unicode order.
  function search(data, query) {
    var q = query.trim();
    if (!q) return [];
    // An emoji typed or pasted into the search box finds itself.
    var direct = data.byBare[bare(q)];
    if (direct) return [direct];
    var terms = words(q);
    if (!terms.length) return [];
    var whole = plainWords(q).join(" ");
    var scored = [];
    data.all.forEach(function (e) {
      var total = 0;
      var named = false;
      for (var i = 0; i < terms.length; i++) {
        var s = termScore(e, terms[i]);
        if (s < 0) return;
        total += s;
        if (!named && e.nameWords.indexOf(terms[i]) >= 0) named = true;
      }
      if (e.core === whole || e.full === whole) total -= 10;
      else if (e.coreLen === 1 && e.core.indexOf(whole) === 0) total -= 0.5;
      scored.push({ score: total, len: named ? e.coreLen : 99, e: e });
    });
    scored.sort(function (a, b) {
      return a.score - b.score || a.len - b.len || a.e.rank - b.e.rank || a.e.order - b.e.order;
    });
    return scored.slice(0, MAX_RESULTS).map(function (x) {
      return x.e;
    });
  }

  // ---- recently used -------------------------------------------------------

  function recent() {
    try {
      var list = JSON.parse(window.localStorage.getItem(RECENT_KEY) || "[]");
      if (!Array.isArray(list)) return [];
      return list.filter(function (x) {
        return typeof x === "string";
      });
    } catch (e) {
      return [];
    }
  }

  function remember(ch) {
    var list = recent().filter(function (x) {
      return bare(x) !== bare(ch);
    });
    list.unshift(ch);
    try {
      window.localStorage.setItem(RECENT_KEY, JSON.stringify(list.slice(0, RECENT_MAX)));
    } catch (e) {
      /* private mode or storage disabled */
    }
  }

  // ---- roving tabindex -----------------------------------------------------

  // Buttons of a group: one of them is in the Tab order.
  function roving(container) {
    return Array.prototype.slice.call(container.querySelectorAll("button"));
  }

  function setRoving(buttons, index) {
    buttons.forEach(function (b, i) {
      b.tabIndex = i === index ? 0 : -1;
    });
  }

  function moveTo(buttons, index) {
    if (!buttons.length) return;
    var i = Math.max(0, Math.min(buttons.length - 1, index));
    setRoving(buttons, i);
    buttons[i].focus();
    return buttons[i];
  }

  // Buttons per row of a wrapping grid.
  function columns(buttons) {
    if (buttons.length < 2) return 1;
    var top = buttons[0].offsetTop;
    for (var i = 1; i < buttons.length; i++) if (buttons[i].offsetTop !== top) return i;
    return buttons.length;
  }

  // Arrow keys in a grid of buttons; `up` runs when ↑ leaves the first row.
  function gridKey(ev, container, up) {
    var buttons = roving(container);
    var i = buttons.indexOf(document.activeElement);
    if (i < 0) return false;
    var cols = columns(buttons);
    var to = null;
    switch (ev.key) {
      case "ArrowLeft":
        to = i - 1;
        break;
      case "ArrowRight":
        to = i + 1;
        break;
      case "ArrowUp":
        if (i < cols) {
          if (up) {
            ev.preventDefault();
            up();
            return true;
          }
          to = i;
        } else to = i - cols;
        break;
      case "ArrowDown":
        // Into a shorter last row: its last button.
        if (i + cols < buttons.length) to = i + cols;
        else to = Math.floor(i / cols) < Math.floor((buttons.length - 1) / cols) ? buttons.length - 1 : i;
        break;
      case "Home":
        to = ev.ctrlKey ? 0 : i - (i % cols);
        break;
      case "End":
        to = ev.ctrlKey ? buttons.length - 1 : Math.min(buttons.length - 1, i - (i % cols) + cols - 1);
        break;
      case "PageUp":
        to = i - cols * 4;
        break;
      case "PageDown":
        to = Math.min(buttons.length - 1, i + cols * 4);
        break;
      default:
        return false;
    }
    ev.preventDefault();
    moveTo(buttons, to);
    return true;
  }

  // ---- one picker per field -------------------------------------------------

  function attach(input) {
    if (!input || input.tagName !== "INPUT" || input.getAttribute("data-emoji-ready")) return;
    input.setAttribute("data-emoji-ready", "1");
    var hadFocus = document.activeElement === input;
    var start = input.selectionStart;
    var end = input.selectionEnd;

    // The field and its button share a line.
    var wrap = el("span", "emoji-field");
    input.parentNode.insertBefore(wrap, input);
    wrap.appendChild(input);
    var toggle = el("button", "emoji-toggle");
    toggle.type = "button";
    toggle.setAttribute("aria-label", "Choose emojis");
    toggle.title = "Choose emojis";
    toggle.setAttribute("aria-expanded", "false");
    toggle.appendChild(smiley());
    wrap.appendChild(toggle);
    if (hadFocus) {
      // Moving the field took its focus.
      input.focus({ preventScroll: true });
      try {
        input.setSelectionRange(start, end);
      } catch (e) {
        /* not a text field */
      }
    }

    var p = { input: input, wrap: wrap, toggle: toggle, panel: null, group: 0, data: null, ac: null };
    acAttach(p);
    toggle.addEventListener("click", function () {
      if (isOpen(p)) close(p, false);
      else open(p);
    });
    // Keys of the ":" suggestions first; Escape in the field closes the panel
    // (before app.js cancels an inline edit).
    input.addEventListener("keydown", function (ev) {
      if (acKeydown(p, ev)) return;
      if (ev.key === "Escape" && isOpen(p)) {
        ev.preventDefault();
        ev.stopPropagation();
        close(p, false);
      }
    });
  }

  function isOpen(p) {
    return !!p.panel && !p.panel.hidden && p.wrap.isConnected;
  }

  function build(p) {
    var id = "emoji-panel-" + nextId++;
    var panel = el("div", "emoji-panel");
    panel.id = id;
    panel.setAttribute("role", "group");
    panel.setAttribute("aria-label", "Emoji picker");
    panel.hidden = true;

    var searchBox = el("input", "emoji-search");
    searchBox.type = "search";
    searchBox.placeholder = "Search emojis";
    searchBox.setAttribute("aria-label", "Search emojis");
    searchBox.autocomplete = "off";
    searchBox.spellcheck = false;
    searchBox.setAttribute("enterkeyhint", "done");

    var tabs = el("div", "emoji-tabs");
    tabs.setAttribute("role", "tablist");
    tabs.setAttribute("aria-label", "Categories");

    var recentBox = el("div", "emoji-recent");
    var recentLabel = el("span", "emoji-label", "Recently used");
    recentLabel.id = id + "-recent";
    var recentRow = el("div", "emoji-row");
    recentRow.setAttribute("role", "group");
    recentRow.setAttribute("aria-labelledby", recentLabel.id);
    recentBox.appendChild(recentLabel);
    recentBox.appendChild(recentRow);
    recentBox.hidden = true;

    var status = el("p", "emoji-status");
    status.setAttribute("role", "status");
    status.setAttribute("aria-live", "polite");

    var grid = el("div", "emoji-grid");
    grid.id = id + "-grid";
    grid.setAttribute("role", "group");
    // Firefox makes scrolling boxes a Tab stop of their own; the buttons
    // inside are the stop.
    grid.tabIndex = -1;
    tabs.tabIndex = -1;
    searchBox.setAttribute("aria-controls", grid.id);

    [searchBox, tabs, recentBox, status, grid].forEach(function (n) {
      panel.appendChild(n);
    });
    p.wrap.parentNode.insertBefore(panel, p.wrap.nextSibling);
    p.toggle.setAttribute("aria-controls", id);
    p.panel = panel;
    p.searchBox = searchBox;
    p.tabs = tabs;
    p.recentBox = recentBox;
    p.recentRow = recentRow;
    p.status = status;
    p.grid = grid;
    p.shown = []; // the emojis in the grid

    searchBox.addEventListener("input", function (ev) {
      ev.stopPropagation(); // not a field of the form
      showResults(p);
    });
    searchBox.addEventListener("change", function (ev) {
      ev.stopPropagation();
    });
    searchBox.addEventListener("keydown", function (ev) {
      if (ev.key === "Enter" && !ev.isComposing) {
        // Never submit the form from here.
        ev.preventDefault();
        if (searchBox.value.trim() && p.shown.length) pick(p, p.shown[0]);
      } else if (ev.key === "ArrowDown" && p.shown.length) {
        ev.preventDefault();
        var buttons = roving(grid);
        moveTo(buttons, Math.max(0, buttons.indexOf(grid.querySelector("button[tabindex='0']"))));
      }
    });

    tabs.addEventListener("click", function (ev) {
      var tab = ev.target instanceof Element && ev.target.closest("[role=tab]");
      if (tab) selectGroup(p, +tab.getAttribute("data-group"), false);
    });
    tabs.addEventListener("keydown", function (ev) {
      var buttons = roving(tabs);
      var i = buttons.indexOf(document.activeElement);
      if (i < 0) return;
      var to = { ArrowLeft: i - 1, ArrowRight: i + 1, Home: 0, End: buttons.length - 1 }[ev.key];
      if (to === undefined) return;
      ev.preventDefault();
      to = (to + buttons.length) % buttons.length;
      selectGroup(p, to, true);
    });

    [grid, recentRow].forEach(function (box) {
      box.addEventListener("click", function (ev) {
        var b = ev.target instanceof Element && ev.target.closest("button[data-emoji]");
        if (!b || !p.data) return;
        var e = p.data.byBare[bare(b.getAttribute("data-emoji"))];
        if (e) {
          setRoving(roving(box), roving(box).indexOf(b));
          pick(p, e);
        }
      });
      box.addEventListener("keydown", function (ev) {
        gridKey(
          ev,
          box,
          box === grid
            ? function () {
                searchBox.focus();
              }
            : null
        );
      });
    });

    panel.addEventListener("keydown", function (ev) {
      if (ev.key === "Escape") {
        ev.preventDefault();
        ev.stopPropagation(); // app.js would cancel an inline edit
        close(p, true);
      }
    });
    // Keyboard focus leaving the field and the panel closes it.
    [p.wrap, panel].forEach(function (n) {
      n.addEventListener("focusout", function (ev) {
        var to = ev.relatedTarget;
        if (to instanceof Node && !p.wrap.contains(to) && !panel.contains(to)) close(p, false);
      });
    });
  }

  function emojiButton(e) {
    var b = el("button", "emoji-btn", e.char);
    b.type = "button";
    b.tabIndex = -1;
    b.setAttribute("data-emoji", e.char);
    b.setAttribute("aria-label", e.name);
    b.title = e.name;
    return b;
  }

  function fill(box, list) {
    var frag = document.createDocumentFragment();
    list.forEach(function (e) {
      frag.appendChild(emojiButton(e));
    });
    box.textContent = "";
    box.appendChild(frag);
    var buttons = roving(box);
    if (buttons.length) buttons[0].tabIndex = 0;
  }

  function renderTabs(p) {
    p.tabs.textContent = "";
    p.data.groups.forEach(function (g, i) {
      var t = el("button", "emoji-tab", g.icon);
      t.type = "button";
      t.id = p.panel.id + "-tab-" + i;
      t.setAttribute("role", "tab");
      t.setAttribute("aria-label", g.name);
      t.title = g.name;
      t.setAttribute("aria-controls", p.grid.id);
      t.setAttribute("data-group", String(i));
      p.tabs.appendChild(t);
    });
  }

  function renderRecent(p) {
    var list = [];
    recent().forEach(function (ch) {
      var e = p.data.byBare[bare(ch)];
      if (e) list.push(e);
    });
    fill(p.recentRow, list);
    p.recentBox.hidden = !list.length || !!p.searchBox.value.trim();
  }

  function markTab(p, i) {
    p.group = i;
    var tabs = roving(p.tabs);
    tabs.forEach(function (t, k) {
      t.setAttribute("aria-selected", k === i ? "true" : "false");
    });
    setRoving(tabs, i);
    return tabs[i];
  }

  // A category: the search is cleared.
  function selectGroup(p, i, focusTab) {
    var tab = markTab(p, i);
    if (focusTab && tab) tab.focus();
    p.searchBox.value = "";
    showResults(p);
  }

  // The grid shows the search results, or the selected category.
  function showResults(p) {
    if (!p.data) return; // still loading; shown when it arrives
    var q = p.searchBox.value.trim();
    var g = p.data.groups[p.group];
    var list;
    if (q) {
      list = search(p.data, q);
      p.grid.setAttribute("aria-label", "Search results");
      p.status.textContent = list.length
        ? list.length === 1
          ? "1 emoji"
          : list.length + (list.length === MAX_RESULTS ? "+" : "") + " emojis"
        : "No emoji matches “" + q + "”.";
    } else {
      list = g.items;
      p.grid.setAttribute("aria-label", g.name);
      p.status.textContent = "";
    }
    p.tabs.classList.toggle("searching", !!q);
    p.recentBox.hidden = !!q || !p.recentRow.firstChild;
    p.shown = list;
    fill(p.grid, list);
    p.grid.scrollTop = 0;
  }

  function open(p) {
    if (current && current !== p) close(current, false);
    if (!p.panel) build(p);
    current = p;
    p.panel.hidden = false;
    p.toggle.setAttribute("aria-expanded", "true");
    p.searchBox.value = "";
    p.searchBox.focus();
    if (p.data) {
      renderRecent(p);
      showResults(p);
      return;
    }
    p.status.textContent = "Loading emojis…";
    load().then(
      function (data) {
        if (p.data) return;
        p.data = data;
        renderTabs(p);
        markTab(p, p.group);
        renderRecent(p);
        showResults(p); // with what was typed meanwhile
      },
      function (err) {
        var why = err && err.message ? err.message : String(err);
        p.status.textContent = "Could not load the emojis (" + why + "). Close the panel and try again.";
      }
    );
  }

  function close(p, restoreFocus) {
    if (!p.panel) return;
    p.panel.hidden = true;
    p.toggle.setAttribute("aria-expanded", "false");
    if (current === p) current = null;
    if (restoreFocus && p.toggle.isConnected) p.toggle.focus();
  }

  // Append to the field (space-separated, the field's format) unless it is
  // there already, and tell the page.
  function pick(p, e) {
    var input = p.input;
    var have = input.value.split(/[\s,]+/).some(function (x) {
      return x && bare(x) === bare(e.char);
    });
    if (have) {
      p.status.textContent = e.char + " is already in the field.";
    } else {
      var v = input.value.replace(/\s+$/, "");
      input.value = v ? v + " " + e.char : e.char;
      input.dispatchEvent(new Event("input", { bubbles: true }));
      p.status.textContent = "Added " + e.char + " " + e.name + ".";
    }
    // The recent row updates on the next open, so nothing jumps now.
    remember(e.char);
  }

  // Is `ch` one of the emojis in `text` (the field's format)?
  function hasEmoji(text, ch) {
    return text.split(/[\s,]+/).some(function (x) {
      return x && bare(x) === bare(ch);
    });
  }

  // ---- ":" suggestions --------------------------------------------------------
  //
  // Typing ":" in the field starts a search: the words typed after it (up to
  // the caret) are the query, and a list under the field (a combobox's
  // listbox; the focus stays in the field) shows the best matches, the first
  // highlighted, or the recently used emojis for a bare ":". ↑/↓ move the
  // highlight; Space, Enter, Tab or a click replace ":query" with the emoji
  // and a space. Escape closes the list and keeps the text; so do moving the
  // caret away, deleting the ":", a character that cannot be part of a name
  // and leaving the field.

  var QUERY_CHAR = (function () {
    try {
      return new RegExp("[\\p{L}\\p{N}_'’+-]", "u");
    } catch (e) {
      return /[0-9A-Za-zÀ-ɏ_'’+-]/;
    }
  })();

  // The search being typed: the caret right after ":" and name characters.
  function tokenAt(input) {
    var v = input.value;
    var caret = input.selectionStart;
    if (caret == null || caret !== input.selectionEnd) return null;
    var i = caret;
    while (i > 0 && QUERY_CHAR.test(v.charAt(i - 1))) i--;
    if (i === 0 || v.charAt(i - 1) !== ":") return null;
    if (caret < v.length && QUERY_CHAR.test(v.charAt(caret))) return null; // inside a word
    return { start: i - 1, query: v.slice(i, caret) };
  }

  function acAttach(p) {
    var input = p.input;
    var id = "emoji-ac-" + nextId++;
    var box = el("div", "emoji-suggest");
    box.hidden = true;
    var note = el("p", "emoji-suggest-note");
    var list = el("ul", "emoji-suggest-list");
    list.id = id;
    list.setAttribute("role", "listbox");
    list.setAttribute("aria-label", "Emoji suggestions");
    var keys = el("p", "emoji-suggest-keys", "Space or Enter inserts, Esc closes");
    keys.setAttribute("aria-hidden", "true");
    box.appendChild(note);
    box.appendChild(list);
    box.appendChild(keys);
    // The result count for screen readers (the field keeps the focus).
    var live = el("span", "sr-only");
    live.setAttribute("role", "status");
    live.setAttribute("aria-live", "polite");
    p.wrap.appendChild(box);
    p.wrap.appendChild(live);

    input.setAttribute("role", "combobox");
    input.setAttribute("aria-autocomplete", "list");
    input.setAttribute("aria-controls", id);
    input.setAttribute("aria-expanded", "false");
    input.autocomplete = "off"; // no browser suggestions over the list
    input.spellcheck = false;

    p.ac = {
      box: box,
      note: note,
      list: list,
      keys: keys,
      live: live,
      open: false,
      start: -1, // where the ":" is
      query: "",
      items: [],
      active: -1,
      timer: 0,
      waiting: false,
      failed: "",
    };

    input.addEventListener("input", function (ev) {
      acInput(p, ev);
    });
    input.addEventListener("blur", function () {
      acClose(p);
    });
    // The caret moved (arrows, Home/End, a click): the search may be over.
    input.addEventListener("keyup", function () {
      acSync(p);
    });
    input.addEventListener("click", function () {
      acSync(p);
    });
    // A click on the list must not take the focus from the field.
    box.addEventListener("mousedown", function (ev) {
      ev.preventDefault();
    });
    list.addEventListener("click", function (ev) {
      var o = ev.target instanceof Element && ev.target.closest("[role=option]");
      if (o && p.ac.open) acPick(p, p.ac.items[+o.getAttribute("data-index")]);
    });
    list.addEventListener("mousemove", function (ev) {
      var o = ev.target instanceof Element && ev.target.closest("[role=option]");
      if (o && +o.getAttribute("data-index") !== p.ac.active) acHighlight(p, +o.getAttribute("data-index"));
    });
  }

  function acInput(p, ev) {
    var ac = p.ac;
    var tok = tokenAt(p.input);
    if (ac.open) {
      if (tok && tok.start === ac.start) {
        if (tok.query !== ac.query) {
          ac.query = tok.query;
          acRender(p);
        }
        return;
      }
      // A space that came without a keydown we could take (virtual
      // keyboards): pick, as Space does.
      var caret = p.input.selectionStart;
      if (ev.data === " " && ac.items.length && p.input.value.slice(ac.start, caret) === ":" + ac.query + " ") {
        acPick(p, ac.items[ac.active], caret);
        return;
      }
      acClose(p);
    }
    // Only a typed ":" starts a search (not a paste, not the caret moving
    // back to an old one).
    if (tok && !tok.query && typeof ev.data === "string" && ev.data.slice(-1) === ":") acOpen(p, tok.start);
  }

  function acSync(p) {
    if (!p.ac.open) return;
    var tok = tokenAt(p.input);
    if (!tok || tok.start !== p.ac.start || tok.query !== p.ac.query) acClose(p);
  }

  // Returns true when the key was for the list.
  function acKeydown(p, ev) {
    var ac = p.ac;
    if (!ac.open || ev.isComposing || ev.keyCode === 229) return false;
    var plain = !ev.ctrlKey && !ev.metaKey && !ev.altKey;
    var n = ac.items.length;
    switch (ev.key) {
      case "ArrowDown":
      case "ArrowUp":
        if (!n || !plain) return false;
        ev.preventDefault();
        acHighlight(p, (ac.active + (ev.key === "ArrowDown" ? 1 : n - 1)) % n);
        return true;
      case "Enter":
        ev.preventDefault(); // never submits the form while searching
        if (n) acPick(p, ac.items[ac.active]);
        return true;
      case " ":
        if (!plain) return false;
        if (n) {
          ev.preventDefault();
          acPick(p, ac.items[ac.active]);
        } else acClose(p); // and the space is typed
        return true;
      case "Tab":
        // Tab completes and stays in the field (Shift+Tab just leaves).
        if (n && plain && !ev.shiftKey) {
          ev.preventDefault();
          acPick(p, ac.items[ac.active]);
        } else acClose(p);
        return true;
      case "Escape":
        ev.preventDefault();
        ev.stopPropagation(); // app.js would cancel an inline edit
        acClose(p);
        return true;
    }
    return false;
  }

  function acOpen(p, start) {
    if (acCurrent && acCurrent !== p) acClose(acCurrent);
    if (isOpen(p)) close(p, false); // one picker at a time
    acCurrent = p;
    var ac = p.ac;
    ac.open = true;
    ac.start = start;
    ac.query = "";
    ac.failed = ""; // a failed load is tried again
    acRender(p);
  }

  function acClose(p) {
    var ac = p.ac;
    if (!ac || !ac.open) return;
    ac.open = false;
    ac.items = [];
    ac.active = -1;
    ac.box.hidden = true;
    ac.list.textContent = "";
    clearTimeout(ac.timer);
    p.input.setAttribute("aria-expanded", "false");
    p.input.removeAttribute("aria-activedescendant");
    if (acCurrent === p) acCurrent = null;
  }

  // What a bare ":" offers: the recently used emojis, else the common ones;
  // not those in the field already.
  function acDefaults(p, data) {
    var v = p.input.value;
    var other = v.slice(0, p.ac.start) + " " + v.slice(p.ac.start + 1);
    function fresh(e) {
      return e && !hasEmoji(other, e.char);
    }
    var list = recent()
      .map(function (ch) {
        return data.byBare[bare(ch)];
      })
      .filter(fresh);
    if (list.length) return { items: list, label: "Recently used" };
    return { items: data.common.filter(fresh), label: "Common emojis" };
  }

  function acRender(p) {
    var ac = p.ac;
    var data = loaded;
    var items = [];
    var note = "";
    var label = "Emoji suggestions";
    var say;
    if (!data) {
      note = ac.failed ? ac.failed : "Loading emojis…";
      say = note;
      if (!ac.failed && !ac.waiting) {
        ac.waiting = true;
        load().then(
          function () {
            ac.waiting = false;
            if (ac.open) acRender(p); // with what was typed meanwhile
          },
          function (err) {
            ac.waiting = false;
            ac.failed = "Could not load the emojis (" + (err && err.message ? err.message : String(err)) + ").";
            if (ac.open) acRender(p);
          }
        );
      }
    } else if (!ac.query) {
      var d = acDefaults(p, data);
      items = d.items.slice(0, AC_MAX);
      note = items.length ? d.label : "";
      label = d.label;
      say = items.length ? plural(items.length, "emoji") + ", " + d.label.toLowerCase() : "";
    } else {
      var found = search(data, ac.query);
      items = found.slice(0, AC_MAX);
      if (items.length) {
        say =
          found.length > items.length
            ? items.length + " of " + found.length + (found.length === MAX_RESULTS ? "+" : "") + " emojis"
            : plural(items.length, "emoji");
      } else {
        note = "No emoji matches “" + ac.query + "”.";
        say = note;
      }
    }
    ac.items = items;
    var frag = document.createDocumentFragment();
    items.forEach(function (e, i) {
      var o = el("li", "emoji-option");
      o.id = ac.list.id + "-" + i;
      o.setAttribute("role", "option");
      o.setAttribute("data-index", String(i));
      o.title = e.name; // when cut short
      var c = el("span", "emoji-option-char", e.char);
      c.setAttribute("aria-hidden", "true");
      o.appendChild(c);
      o.appendChild(el("span", "emoji-option-name", e.name));
      frag.appendChild(o);
    });
    ac.list.textContent = "";
    ac.list.appendChild(frag);
    ac.list.setAttribute("aria-label", label);
    ac.list.hidden = !items.length;
    ac.keys.hidden = !items.length;
    ac.note.textContent = note;
    ac.note.hidden = !note;
    ac.box.hidden = !items.length && !note;
    p.input.setAttribute("aria-expanded", items.length ? "true" : "false");
    acHighlight(p, items.length ? 0 : -1);
    acPlace(p);
    announce(p, say || "", true);
  }

  function plural(n, word) {
    return n + " " + word + (n === 1 ? "" : "s");
  }

  function acHighlight(p, i) {
    var ac = p.ac;
    var options = ac.list.children;
    ac.active = i;
    for (var k = 0; k < options.length; k++) options[k].setAttribute("aria-selected", k === i ? "true" : "false");
    if (i >= 0 && options[i]) p.input.setAttribute("aria-activedescendant", options[i].id);
    else p.input.removeAttribute("aria-activedescendant");
  }

  // Under the field (above it when there is no room below), fixed so a
  // card's overflow does not cut it.
  function acPlace(p) {
    var box = p.ac.box;
    if (!p.ac.open || box.hidden) return;
    if (!p.wrap.isConnected) {
      acClose(p);
      return;
    }
    var r = p.wrap.getBoundingClientRect();
    var f = p.input.getBoundingClientRect();
    var vw = document.documentElement.clientWidth;
    var vh = document.documentElement.clientHeight;
    box.style.setProperty("--emoji-field-width", r.width + "px"); // at least as wide
    var w = box.offsetWidth;
    var h = box.offsetHeight;
    var x = Math.max(4, Math.min(r.left, vw - w - 4));
    var y = f.bottom + 3;
    if (y + h > vh - 4 && f.top - h - 3 >= 4) y = f.top - h - 3;
    box.style.left = x + "px";
    box.style.top = y + "px";
    box.classList.toggle("offscreen", f.bottom < 0 || f.top > vh);
  }

  // Counts wait until typing pauses; a pick is said at once.
  function announce(p, text, later) {
    var ac = p.ac;
    clearTimeout(ac.timer);
    if (!later) {
      ac.live.textContent = text;
      return;
    }
    ac.timer = setTimeout(function () {
      ac.live.textContent = text;
    }, 500);
  }

  // Replace ":query" (up to `end`, else its end) with the emoji and a space,
  // the caret after them, unless the emoji is in the field already.
  function acPick(p, e, end) {
    var ac = p.ac;
    var input = p.input;
    var v = input.value;
    var start = ac.start;
    var stop = end != null ? end : start + 1 + ac.query.length;
    acClose(p);
    if (!e) return;
    var before = v.slice(0, start);
    var after = v.slice(stop).replace(/^[ \t]+/, "");
    var have = hasEmoji(before + " " + after, e.char);
    var sep = before && !/\s$/.test(before) ? " " : "";
    var text = have ? sep : sep + e.char + " ";
    input.value = before + text + after;
    var caret = before.length + text.length;
    try {
      input.setSelectionRange(caret, caret);
    } catch (x) {
      /* not a text field */
    }
    input.dispatchEvent(new Event("input", { bubbles: true }));
    remember(e.char);
    announce(p, have ? e.char + " is already in the field." : "Added " + e.char + " " + e.name + ".", false);
  }

  // ---- page-wide -----------------------------------------------------------

  document.addEventListener(
    "pointerdown",
    function (ev) {
      var p = current;
      if (!p) return;
      if (!p.wrap.isConnected) {
        current = null;
        return;
      }
      var t = ev.target;
      if (t instanceof Node && (p.wrap.contains(t) || p.panel.contains(t))) return;
      close(p, false);
    },
    true
  );

  // The ":" list follows its field.
  window.addEventListener(
    "scroll",
    function () {
      if (acCurrent) acPlace(acCurrent);
    },
    true
  );
  window.addEventListener("resize", function () {
    if (acCurrent) acPlace(acCurrent);
  });
  document.addEventListener("selectionchange", function () {
    if (acCurrent && document.activeElement === acCurrent.input) acSync(acCurrent);
  });

  function enhance(root) {
    if (!root || !root.querySelectorAll) return;
    if (root.matches && root.matches("input[data-emoji-picker]")) attach(root);
    root.querySelectorAll("input[data-emoji-picker]").forEach(attach);
  }

  window.stickpileEmoji = { attach: attach };

  document.addEventListener("htmx:load", function (e) {
    enhance(e.target);
  });
  enhance(document);
})();
