fn table() -> &'static HashMap<&'static str, &'static str> {
    static TABLE: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    TABLE.get_or_init(|| NAMES.iter().copied().collect())
}

/// Words for an emoji token (variation selectors and skin tones already
/// stripped). ZWJ sequences fall back to their first emoji (🤷‍♂ -> 🤷).
pub(crate) fn names(emoji: &str) -> Option<&'static str> {
    let t = table();
    t.get(emoji).copied().or_else(|| {
        let first = emoji.chars().next()?;
        let mut buf = [0u8; 4];
        t.get(&*first.encode_utf8(&mut buf)).copied()
    })
}
